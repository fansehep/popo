#pragma once
#include <cstdint>
#include <map>
#include <optional>
#include <string>
#include <vector>
#include "src/storage/common.h"
#include "src/storage/redo_log.h"
#include "src/type/tuple.h"

namespace popo::txn
{

enum class TxnState : uint8_t
{
    RUNNING = 0,
    COMMITTED = 1,
    ABORTED = 2,
};

// SQL standard isolation levels.
enum class IsolationLevel : uint8_t
{
    ReadUncommitted = 0,
    ReadCommitted = 1,
    RepeatableRead = 2,
    Serializable = 3,
};

// A read snapshot: everything committed strictly before `csn` is visible,
// plus the owning transaction's own buffered writes.
struct Snapshot
{
    uint64_t csn = 0;
};

class Transaction
{
public:
    explicit Transaction(popo::storage::txn_id_t txn_id) : txn_id_(txn_id), state_(TxnState::RUNNING) { }

    popo::storage::txn_id_t txn_id() const { return txn_id_; }
    TxnState state() const { return state_; }
    void set_state(TxnState state) { state_ = state; }

    popo::storage::lsn_t start_lsn() const { return start_lsn_; }
    void set_start_lsn(popo::storage::lsn_t lsn) { start_lsn_ = lsn; }

    // Last log record produced by this txn; the prev_lsn of the next record.
    popo::storage::lsn_t last_lsn() const { return last_lsn_; }
    void set_last_lsn(popo::storage::lsn_t lsn) { last_lsn_ = lsn; }

    IsolationLevel isolation() const { return isolation_; }
    void set_isolation(IsolationLevel level) { isolation_ = level; }

    const Snapshot & snapshot() const { return snapshot_; }
    void set_snapshot(Snapshot snap) { snapshot_ = snap; }

    // Read-committed takes a fresh snapshot per statement, not per read, so a
    // statement that touches a table twice still sees one consistent image.
    uint64_t statement_csn() const { return statement_csn_; }
    void set_statement_csn(uint64_t csn) { statement_csn_ = csn; }

    uint64_t commit_csn() const { return commit_csn_; }
    void set_commit_csn(uint64_t csn) { commit_csn_ = csn; }

    // Write set for rollback: stores log records generated by this txn.
    const std::vector<popo::storage::LogRecord> & write_set() const { return write_set_; }
    void add_to_write_set(const popo::storage::LogRecord & record) { write_set_.push_back(record); }

    bool is_running() const { return state_ == TxnState::RUNNING; }
    bool is_committed() const { return state_ == TxnState::COMMITTED; }
    bool is_aborted() const { return state_ == TxnState::ABORTED; }

    // ---- MVCC write overlay (buffered until commit) ----
    // Per table, a map from primary-key value to the pending row. A disengaged
    // optional marks a pending delete. Ordered by PK for deterministic install.
    struct TableOverlay
    {
        std::map<popo::type::Value, std::optional<popo::type::Row>> rows;
    };
    std::map<std::string, TableOverlay> & overlay() { return overlay_; }
    const std::map<std::string, TableOverlay> & overlay() const { return overlay_; }

    // Read ranges observed (table -> [low, high] PK bounds) for serializable
    // conflict detection. A disengaged bound means unbounded.
    struct ReadRange
    {
        std::optional<popo::type::Value> low;
        std::optional<popo::type::Value> high;
    };
    std::map<std::string, std::vector<ReadRange>> & read_set() { return read_set_; }

private:
    popo::storage::txn_id_t txn_id_;
    TxnState state_;
    popo::storage::lsn_t start_lsn_ = popo::storage::INVALID_LSN;
    popo::storage::lsn_t last_lsn_ = popo::storage::INVALID_LSN;
    IsolationLevel isolation_ = IsolationLevel::ReadCommitted;
    Snapshot snapshot_{};
    uint64_t statement_csn_ = 0;
    uint64_t commit_csn_ = 0;
    std::vector<popo::storage::LogRecord> write_set_;
    std::map<std::string, TableOverlay> overlay_;
    std::map<std::string, std::vector<ReadRange>> read_set_;
};

} // namespace popo::txn